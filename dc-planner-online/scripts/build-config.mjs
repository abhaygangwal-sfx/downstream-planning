#!/usr/bin/env node
/* Writes public/config.js from environment variables (or a local .env file).
   Run by the host's build step (Netlify / Vercel / Cloudflare Pages) and locally before testing.
   Only the PUBLIC anon / publishable key belongs here. The build fails if a secret key is supplied. */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = join(root, '.env');
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}

const url = (process.env.SUPABASE_URL || '').trim().replace(/\/+$/, '');
const key = (process.env.SUPABASE_ANON_KEY || process.env.SUPABASE_PUBLISHABLE_KEY || '').trim();

function fail(msg) { console.error('build-config: ' + msg); process.exit(1); }
if (!url) fail('SUPABASE_URL is not set.');
if (!/^https:\/\/[^/]+$/.test(url) && !/^http:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/.test(url)) fail('SUPABASE_URL must look like https://<project-ref>.supabase.co');
if (!key) fail('SUPABASE_ANON_KEY is not set.');
let role = '';
if (key.startsWith('sb_secret_')) role = 'service_role';
else if (key.startsWith('sb_publishable_')) role = 'anon';
else { try { role = JSON.parse(Buffer.from(key.split('.')[1], 'base64url').toString()).role || ''; } catch { role = ''; } }
if (role === 'service_role') fail('That is a service-role / secret key. Never ship it to the browser. Use the anon (publishable) key, and rotate the secret key if it was exposed.');
if (process.env.SUPABASE_SERVICE_ROLE_KEY && process.env.SUPABASE_SERVICE_ROLE_KEY === key) fail('SUPABASE_ANON_KEY equals SUPABASE_SERVICE_ROLE_KEY.');

const out = join(root, 'public', 'config.js');
writeFileSync(out, '/* Generated by scripts/build-config.mjs. Do not edit or commit. Public values only. */\n'
  + 'window.APP_CONFIG = ' + JSON.stringify({ SUPABASE_URL: url, SUPABASE_ANON_KEY: key }, null, 2) + ';\n');
console.log('build-config: wrote public/config.js for ' + url);
